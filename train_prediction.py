import os
import sys
import glob
import json
import random
import numpy as np
import evaluate
from datasets import Dataset, DatasetDict
from transformers import (
    AutoTokenizer, 
    DataCollatorWithPadding,
    AutoModelForSequenceClassification, 
    TrainingArguments, 
    Trainer
)
from sklearn.metrics import precision_score, recall_score, f1_score, roc_auc_score, average_precision_score

# ==========================================
# 1. Custom Dataset Loader (JSON Metadata & 60/40 Split)
# ==========================================
def load_termbench_dataset(base_dir="dataset", test_size=0.4, seed=42):
    """
    Reads the Python dataset generated by termination_dataset_generation.py.
    Extracts labels and metadata from JSONs, and splits 60% Train / 40% Test.
    """
    py_dir = os.path.join(base_dir, "python")
    if not os.path.exists(py_dir):
        raise FileNotFoundError(f"Python dataset directory not found at {py_dir}. Please run the generator first.")
        
    json_files = glob.glob(os.path.join(py_dir, "*.json"))
    
    all_samples = []
    print(f"Discovered {len(json_files)} metadata JSONs in {py_dir}.")
    
    for jf in json_files:
        py_file = jf.replace(".json", ".py")
        if not os.path.exists(py_file):
            continue
            
        with open(jf, "r", encoding="utf-8") as f:
            meta = json.load(f)
            
        with open(py_file, "r", encoding="utf-8") as f:
            content = f.read()
            
        # Route terminating to 1 (POSITIVE), non_terminating to 0 (NEGATIVE)
        label_id = 1 if meta.get("label") == "terminating" else 0
        
        all_samples.append({
            "text": content,
            "label": label_id,
            "category": meta.get("category", "unknown"),
            "domain": meta.get("domain", "unknown"),
            "length": meta.get("length", "unknown")
        })
        
    if not all_samples:
        raise ValueError("No valid sample pairs (.py and .json) found.")

    # Shuffle and split 0.6 Train / 0.4 Test
    random.seed(seed)
    random.shuffle(all_samples)
    
    split_idx = int(len(all_samples) * (1 - test_size))
    train_samples = all_samples[:split_idx]
    test_samples = all_samples[split_idx:]
    
    print(f"Split dataset: {len(train_samples)} Train / {len(test_samples)} Test")

    # Pivot list of dicts to dict of lists for Hugging Face mapping
    train_data = {k: [d[k] for d in train_samples] for k in train_samples[0].keys()}
    test_data = {k: [d[k] for d in test_samples] for k in test_samples[0].keys()}
    
    return DatasetDict({
        "train": Dataset.from_dict(train_data),
        "test": Dataset.from_dict(test_data)
    })

# ==========================================
# 2. Initialization & Preprocessing
# ==========================================
if len(sys.argv) > 1:
    arg1 = sys.argv[1]
    arg2 = sys.argv[2]
else:
    arg1 = "microsoft/codebert-base" 
    arg2 = "TermBench"

print(f'Basemodel: {arg1}  Dataset: {arg2}')

# Load and split dataset
termination_dataset = load_termbench_dataset(base_dir="dataset", test_size=0.4)

tokenizer = AutoTokenizer.from_pretrained(arg1)

# Assign a padding token for GPT-2 based models if missing
if 'gpt2' in arg1.lower() and tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token

def preprocess_function(examples):
    return tokenizer(
        examples["text"],
        truncation=True,
        max_length=512 
    )

tokenized_dataset = termination_dataset.map(preprocess_function, batched=True)
data_collator = DataCollatorWithPadding(tokenizer=tokenizer)

# ==========================================
# 3. Metrics Definition
# ==========================================
accuracy = evaluate.load("accuracy")
precision = evaluate.load("precision")
recall = evaluate.load("recall")
f1 = evaluate.load("f1")

def _p_y1_from_logits(z: np.ndarray) -> np.ndarray:
    if z.ndim == 1:
        return 1.0 / (1.0 + np.exp(-z))
    if z.ndim == 2 and z.shape[1] == 1:
        return 1.0 / (1.0 + np.exp(-z[:, 0]))
    if z.ndim == 2 and z.shape[1] == 2:
        e = np.exp(z - z.max(axis=1, keepdims=True))
        p = e / e.sum(axis=1, keepdims=True)
        return p[:, 1]
    raise ValueError(f"Unsupported logits shape: {z.shape}")

def compute_metrics(eval_pred):
    logits, labels = eval_pred
    preds = np.argmax(logits, axis=-1)

    accuracy_result = accuracy.compute(predictions=preds, references=labels)
    precision_result = precision.compute(predictions=preds, references=labels, average="weighted")
    recall_result = recall.compute(predictions=preds, references=labels, average="weighted")
    f1_result = f1.compute(predictions=preds, references=labels, average="weighted")

    y = np.asarray(labels).ravel().astype(int)
    z = np.asarray(logits)

    try:
        auroc_logit1 = roc_auc_score(y, z[:, 1])
    except Exception:
        auroc_logit1 = float("nan")

    try:
        scores_pos = _p_y1_from_logits(z)
        auroc_prob = roc_auc_score(y, scores_pos)
    except Exception:
        auroc_prob = float("nan")

    try:
        if z.ndim == 2 and z.shape[1] == 2:
            auroc_margin = roc_auc_score(y, z[:, 1] - z[:, 0])
        else:
            auroc_margin = float("nan")
    except Exception:
        auroc_margin = float("nan")

    try:
        map_score = average_precision_score(y, preds, average="macro")
    except Exception:
        map_score = float("nan")

    try:
        if np.unique(y).size == 2:
            ap_pos = average_precision_score(y, scores_pos, pos_label=1)
            ap_neg = average_precision_score(1 - y, 1.0 - scores_pos, pos_label=1)
            mAP_balanced = 0.5 * (ap_pos + ap_neg)
        else:
            mAP_balanced = float("nan")
    except Exception:
        mAP_balanced = float("nan")

    return {
        "accuracy": accuracy_result["accuracy"],
        "precision": precision_result["precision"],
        "recall": recall_result["recall"],
        "f1": f1_result["f1"],
        "mAP": map_score,
        "mAP_balanced": mAP_balanced,
        "auroc_logit1": auroc_logit1,
        "auroc_prob": auroc_prob,
        "auroc_margin": auroc_margin,
    }

# ==========================================
# 4. Model & Trainer Configuration
# ==========================================
id2label = {0: "NEGATIVE", 1: "POSITIVE"}
label2id = {"NEGATIVE": 0, "POSITIVE": 1}

model = AutoModelForSequenceClassification.from_pretrained(
    arg1, 
    num_labels=2, 
    id2label=id2label, 
    label2id=label2id,
    use_safetensors=True
)

if 'gpt2' in arg1.lower():
    model.config.pad_token_id = tokenizer.pad_token_id

training_args = TrainingArguments(
    output_dir=f'outputs/{arg2}/{arg1}',
    logging_dir=f"logs/{arg2}/{arg1}/runs",
    report_to=['tensorboard'],
    learning_rate=2e-5,
    per_device_train_batch_size=2,  
    per_device_eval_batch_size=4,   
    gradient_accumulation_steps=4,  
    fp16=True,                      
    num_train_epochs=1,     
    weight_decay=0.01,
    eval_strategy="steps",
    eval_steps=15,
    save_strategy="epoch",
    load_best_model_at_end=False,
    push_to_hub=False,
)

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=tokenized_dataset["train"],
    eval_dataset=tokenized_dataset["test"],
    processing_class=tokenizer,
    data_collator=data_collator,
    compute_metrics=compute_metrics,
)

# ==========================================
# 5. Training & Granular Evaluation
# ==========================================
print("\n--- Starting Training ---")
trainer.train()

test_ds = tokenized_dataset["test"]

print("\n=============================================")
print("          EVALUATION RESULTS                 ")
print("=============================================")

print("\n--- Overall Test Metrics ---")
overall_metrics = trainer.evaluate(test_ds, metric_key_prefix="overall")
print(overall_metrics)

print("\n--- Metrics per Category ---")
unique_categories = list(set(test_ds["category"]))
for cat in unique_categories:
    cat_ds = test_ds.filter(lambda x: x["category"] == cat, desc=f"Filtering {cat}")
    if len(cat_ds) > 0:
        metrics = trainer.evaluate(cat_ds, metric_key_prefix=f"cat_{cat}")
        print(f"\n[{cat.upper()}] Metrics: {metrics}")

print("\n--- Metrics per Domain ---")
unique_domains = list(set(test_ds["domain"]))
for dom in unique_domains:
    dom_ds = test_ds.filter(lambda x: x["domain"] == dom, desc=f"Filtering {dom}")
    if len(dom_ds) > 0:
        metrics = trainer.evaluate(dom_ds, metric_key_prefix=f"dom_{dom}")
        print(f"\n[{dom.upper()}] Metrics: {metrics}")
        
print("\n--- Metrics per Code Length ---")
unique_lengths = list(set(test_ds["length"]))
for length in unique_lengths:
    len_ds = test_ds.filter(lambda x: x["length"] == length, desc=f"Filtering {length}")
    if len(len_ds) > 0:
        metrics = trainer.evaluate(len_ds, metric_key_prefix=f"len_{length}")
        print(f"\n[{length.upper()}] Metrics: {metrics}")