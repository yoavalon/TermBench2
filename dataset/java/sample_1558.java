public class sample_1558 {
    public static void particle_swarm_optimization() {
        int x = 0;
        while (true) {
            x += 1;
            if (x > 10) {
                x = 0;
            }
            System.out.println(x);
        }
    }

    public static void main(String[] args) {
        particle_swarm_optimization();
    }
}