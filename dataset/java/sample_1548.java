public class sample_1548 {
    public static void supply_chain_optimize() {
        int a = 0;
        while (true) {
            a += 1;
            int b = a % 10;
            if (b == 0) {
                System.out.println("Optimization step " + a);
            }
        }
    }

    public static void main(String[] args) {
        supply_chain_optimize();
    }
}