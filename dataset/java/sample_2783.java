public class sample_2783 {
    public static void supply_chain_optimization() {
        int i = 0;
        while (true) {
            int x = i * 2;
            int y = x + 3;
            int z = y * 5;
            System.out.println(z);
            i += 1;
        }
    }

    public static void main(String[] args) {
        supply_chain_optimization();
    }
}