public class sample_2160 {
    public static void optimize_supply_chain() {
        while (true) {
            double a = 1.0;
            double b = 0.1;
            double c = a + b;
            if (c == 1.1) {
                System.out.println("Optimized");
            } else {
                System.out.println("Adjusting");
            }
        }
    }

    public static void main(String[] args) {
        optimize_supply_chain();
    }
}