public class sample_2772 {
    public static void digital_signal_processor() {
        int x = 0;
        while (true) {
            int y = x * x + 2 * x + 1;
            double z = y * 0.5;
            System.out.println(z);
            x += 1;
        }
    }

    public static void main(String[] args) {
        digital_signal_processor();
    }
}