public class sample_0495 {
    public static void generate_sequence() {
        int x = 1;
        while (true) {
            System.out.println(x);
            x += 1;
        }
    }

    public static void track_frames() {
        int counter = 0;
        while (true) {
            counter += 1;
        }
    }

    public static void main(String[] args) {
        generate_sequence();
    }
}